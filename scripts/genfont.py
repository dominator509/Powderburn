def create_png(width, height, pixels):
    """Create a minimal PNG from raw pixel data."""
    # Each pixel is 4 bytes (RGBA)
    raw = b''
    for y in range(height):
        raw += b'\x00'  # filter byte
        for x in range(width):
            i = (y * width + x) * 4
            raw += bytes(pixels[i:i+4])
    
    def chunk(chunk_type, data):
        c = chunk_type + data
        return struct.pack('>I', len(data)) + c + struct.pack('>I', zlib.crc32(c) & 0xFFFFFFFF)
    
    sig = b'\x89PNG\r\n\x1a\n'
    ihdr = struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0)  # 8-bit RGBA
    idat = zlib.compress(raw)
    
    return sig + chunk(b'IHDR', ihdr) + chunk(b'IDAT', idat) + chunk(b'IEND', b'')

def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else '/root/powderburn/assets/font.png'
    
    # Create font atlas: 96 glyphs (32-127) in a 16x6 grid, each 8x8 pixels
    glyph_w, glyph_h = 8, 8
    cols, rows = 16, 6
    tex_w, tex_h = cols * glyph_w, rows * glyph_h
    
    pixels = bytearray(tex_w * tex_h * 4)
    
    for i in range(96):
        ascii_code = i + 32
        gx = i % cols
        gy = i // cols
        bx = gx * glyph_w
        by = gy * glyph_h
        
        for row in range(glyph_h):
            byte_val = FONT_DATA[i * glyph_h + row] if i * glyph_h + row < len(FONT_DATA) else 0
            for col in range(glyph_w):
                pixel_on = (byte_val >> (7 - col)) & 1
                px = bx + col
                py = by + row
                idx = (py * tex_w + px) * 4
                if pixel_on:
                    pixels[idx:idx+4] = [255, 255, 255, 255]  # white
                else:
                    pixels[idx:idx+4] = [0, 0, 0, 0]  # transparent
    
    png_data = create_png(tex_w, tex_h, bytes(pixels))
    os.makedirs(os.path.dirname(out_path) or '.', exist_ok=True)
    with open(out_path, 'wb') as f:
        f.write(png_data)
    print(f"Font atlas written: {out_path} ({tex_w}x{tex_h}, {len(png_data)} bytes)")

if __name__ == '__main__':
    main()
